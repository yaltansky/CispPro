(
	[CLASS_ID] ASC,
	[NAME] ASC
)
GO

IF NOT EXISTS (SELECT * FROM sys.foreign_keys WHERE object_id = OBJECT_ID(N'[FK_PRODMETA_TEMPLATES_CLASS_ID]') AND parent_object_id = OBJECT_ID(N'[PRODMETA_TEMPLATES]'))
