
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[PRODMETA_TEMPLATES]') AND type in (N'U'))
BEGIN
CREATE TABLE [PRODMETA_TEMPLATES](
	[CLASS_ID] [int] NULL,
	[TEMPLATE_ID] [int] IDENTITY(1,1) NOT NULL,
	[NAME] [varchar](250) NULL,
	[CONTENT] [nvarchar](max) NULL,
	[IS_DELETED] [bit] NOT NULL DEFAULT ((0)),
PRIMARY KEY CLUSTERED 
(
	[TEMPLATE_ID] ASC
)
)
END
GO

IF NOT EXISTS (SELECT * FROM sys.indexes WHERE object_id = OBJECT_ID(N'[PRODMETA_TEMPLATES]') AND name = N'IX_PRODMETA_TEMPLATES')
